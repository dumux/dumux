"""
Generate solution.hh: exact solution and source terms of a plane-strain manufactured
solution for the large-deformation poroelastic model on the unit square.

The displacement d = t phi(x,y) (a, b) has a rank-one gradient, so J = 1 + t (a phi_x + b phi_y)
is linear in time, and so is the fluid pressure. The storage term alpha_B J + S_p p_f is
therefore linear in time and implicit Euler integrates it without time discretization error.
Displacement and fluid pressure vanish on the boundary for all t.
"""

import sympy as sp

x, y, t = sp.symbols("x y t", real=True)
G, K, alpha, Sp, kappa0, mu = sp.symbols("G K alpha Sp kappa0 mu", positive=True)

phi = sp.sin(sp.pi*x)*sp.sin(sp.pi*y)*sp.exp(x/2 + y/4)
pfExact = t*sp.sin(sp.pi*x)*sp.sin(sp.pi*y)*sp.exp(-y/2)

# amplitude such that the largest |1 - J| is 0.45 at t = 1; J spans [0.55, 1.29]
direction = sp.Matrix([2, 1])/sp.sqrt(5)
gradPhi = sp.Matrix([sp.diff(phi, x), sp.diff(phi, y)])
import numpy as np
fGradPhiDir = sp.lambdify((x, y), (direction.T*gradPhi)[0], "numpy")
X, Y = np.meshgrid(np.linspace(0, 1, 401), np.linspace(0, 1, 401))
amplitude = sp.Rational(45, 100)/sp.nsimplify(round(float(np.abs(fGradPhiDir(X, Y)).max()), 4))
ab = amplitude*direction

d = t*phi*ab
F = sp.eye(2) + d.jacobian([x, y])
J = sp.simplify(F.det())
assert sp.simplify(sp.diff(J, t, 2)) == 0

