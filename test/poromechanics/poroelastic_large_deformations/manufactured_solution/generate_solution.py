Piso = G*J**sp.Rational(-2, 3)*(F - (I1 + 1)/3*FinvT)
P = Piso + (psExact - alpha*pfExact)*J*FinvT

divP = sp.Matrix([sp.diff(P[i, 0], x) + sp.diff(P[i, 1], y) for i in range(2)])
fMomentum = -divP

gradPf = sp.Matrix([sp.diff(pfExact, x), sp.diff(pfExact, y)])
q = J*kappa0*J/mu*(Finv*FinvT)*gradPf
fFluid = sp.diff(alpha*J + Sp*pfExact, t) - (sp.diff(q[0], x) + sp.diff(q[1], y))

fJ = sp.lambdify((x, y, t), J, "numpy")
Jt1 = fJ(X, Y, 1.0)
print(f"J at t=1: min {Jt1.min():.4f}, max {Jt1.max():.4f}")


def cxx(name, args, exprs):
    subs, reduced = sp.cse(exprs, symbols=sp.numbered_symbols("s"), optimizations="basic")
    body = [f"    const Scalar {str(s)} = {sp.cxxcode(e, standard='c++17')};" for s, e in subs]
    if len(reduced) == 1:
        body.append(f"    return {sp.cxxcode(reduced[0], standard='c++17')};")
        ret = "Scalar"
    else:
        body.append("    return {" + ", ".join(sp.cxxcode(e, standard='c++17') for e in reduced) + "};")
        ret = f"std::array<Scalar, {len(reduced)}>"
    sig = ", ".join(f"Scalar {a}" for a in args)
    return f"template<class Scalar>\n{ret} {name}({sig})\n{{\n    using std::sin; using std::cos; using std::exp; using std::pow; using std::sqrt;\n" + "\n".join(body) + "\n}\n"


