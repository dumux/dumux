import argparse
import json
import math
import pathlib
import sys


# Newmark comes last with a dashed line, since it coincides with Chung-Hulbert for rho_inf = 1
METHODS = ["ch_1.0", "ch_0.8", "ch_0.5", "ch_0.0", "hht_0.8", "wbz_0.8", "newmark"]
STYLES = {"ch_1.0": "-", "ch_0.8": "-", "ch_0.5": "-", "ch_0.0": "-", "hht_0.8": "--", "wbz_0.8": ":", "newmark": (0, (4, 4))}


def main() -> int:
    parser = argparse.ArgumentParser(description="Plot convergence and dissipation of the generalized-alpha methods.")
    parser.add_argument("--input", required=True, help="Input JSON file generated by test_generalizedalpha")
    parser.add_argument("--output", required=True, help="Output image file (e.g. png)")
    args = parser.parse_args()

    input_path = pathlib.Path(args.input)
    output_path = pathlib.Path(args.output)
    if not input_path.exists():
        print(f"Input file does not exist: {input_path}", file=sys.stderr)
        return 1

    with input_path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)["methods"]

    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not found; skipping plot generation.")
        return 0

    plt.rcParams.update({"font.size": 12, "axes.titlesize": 13, "axes.labelsize": 12,
                         "xtick.labelsize": 11, "ytick.labelsize": 11})

    cmap = plt.get_cmap("tab10").colors
    fig, axes = plt.subplots(2, 2, figsize=(13.0, 10.0), constrained_layout=True)
    (axConvergence, axRadius), (axDamping, axPeriod) = axes

    for i, key in enumerate(METHODS):
        method = data[key]
        color = "k" if key == "newmark" else cmap[i % len(cmap)]
        style = dict(color=color, linestyle=STYLES[key], label=method["name"])

        dts = [p[0] for p in method["convergence"]]
        errors = [p[1] for p in method["convergence"]]
        axConvergence.loglog(dts, errors, marker="o", **style)

        # abscissa: time step size over the period T = 2 pi/omega
        stepPerPeriod = [p[0]/(2.0*math.pi) for p in method["spectralRadius"]]
        axRadius.semilogx(stepPerPeriod, [p[1] for p in method["spectralRadius"]], **style)

        stepPerPeriod = [p[0]/(2.0*math.pi) for p in method["dampingAndPeriod"]]
        axDamping.semilogx(stepPerPeriod, [p[1] for p in method["dampingAndPeriod"]], **style)
        axPeriod.semilogx(stepPerPeriod, [p[2] - 1.0 for p in method["dampingAndPeriod"]], **style)

    dts = [p[0] for p in data["newmark"]["convergence"]]
    e0 = data["newmark"]["convergence"][0][1]
    axConvergence.loglog([dts[0], dts[-1]], [0.3*e0, 0.3*e0*(dts[-1]/dts[0])**2], color="0.5", linestyle="--", linewidth=1.0, label="order 2")
    axConvergence.xaxis.set_minor_formatter(plt.NullFormatter())
    axConvergence.set_xlabel(r"time step size $\Delta t$")
    axConvergence.set_ylabel("largest absolute error at $t=2$")
    axConvergence.set_title("Damped oscillators")
    axConvergence.legend(loc="lower right", fontsize=9)

    axRadius.set_xlabel(r"$\Delta t / T$")
    axRadius.set_ylabel(r"spectral radius $\rho$")
    axRadius.set_title("Spectral radius")
    axRadius.set_xlim(1e-2, 1e5)
    axRadius.set_ylim(-0.02, 1.05)

    axDamping.set_xlabel(r"$\Delta t / T$")
    axDamping.set_ylabel(r"algorithmic damping ratio $\bar\xi$")
    axDamping.set_title("Algorithmic damping")
    axDamping.set_xlim(1e-2, 1e0)
    axDamping.set_ylim(-0.01, 0.3)

    axPeriod.set_xlabel(r"$\Delta t / T$")
    axPeriod.set_ylabel(r"relative period error $(\bar T - T)/T$")
    axPeriod.set_title("Period elongation")
    axPeriod.set_xlim(1e-2, 1e0)
    axPeriod.set_ylim(-0.01, 0.5)

    for ax in axes.flat:
        ax.grid(True, which="both", alpha=0.3)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=180)
    print(f"Wrote plot to {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
