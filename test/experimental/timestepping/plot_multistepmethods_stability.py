import argparse
import json
import math
import pathlib
import sys


def main() -> int:
    parser = argparse.ArgumentParser(description="Plot the stability regions of the BDF methods.")
    parser.add_argument("--input", required=True, help="Input JSON file generated by test_multistepmethods_stability")
    parser.add_argument("--output", required=True, help="Output image file (e.g. png)")
    args = parser.parse_args()

    input_path = pathlib.Path(args.input)
    output_path = pathlib.Path(args.output)
    if not input_path.exists():
        print(f"Input file does not exist: {input_path}", file=sys.stderr)
        return 1

    with input_path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)

    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not found; skipping plot generation.")
        return 0

    plt.rcParams.update({"font.size": 12, "axes.titlesize": 13, "axes.labelsize": 12,
                         "xtick.labelsize": 11, "ytick.labelsize": 11})

    fig, axes = plt.subplots(1, 2, figsize=(13.5, 5.8), constrained_layout=True,
                             gridspec_kw={"width_ratios": [1.25, 1.0]})
    cmap = plt.get_cmap("tab10").colors

    # stability regions: each method is unstable inside its boundary locus
    ax = axes[0]
    for i, k in enumerate(range(5, 0, -1)):
        method = data["methods"][f"bdf{k}"]
        x = [p[0] for p in method["boundaryLocus"]]
        y = [p[1] for p in method["boundaryLocus"]]
        color = cmap[k - 1]
        ax.fill(x, y, color=color, alpha=0.15)
        label = method["name"]
        if k >= 3:
            label += rf" ($\alpha = {method['angle']:.2f}^\circ$)"
        else:
            label += " (A-stable)"
        ax.plot(x, y, color=color, linewidth=1.4, label=label)
        if k >= 3:
            angle = math.radians(method["angle"])
            r = 14.0
            ax.plot([0, -r * math.cos(angle)], [0, r * math.sin(angle)], color=color, linestyle="--", linewidth=1.0)
            ax.plot([0, -r * math.cos(angle)], [0, -r * math.sin(angle)], color=color, linestyle="--", linewidth=1.0)

    ax.axhline(0.0, color="0.7", linewidth=0.8)
    ax.axvline(0.0, color="0.7", linewidth=0.8)
    ax.set_xlim(-8.0, 18.0)
    ax.set_ylim(-13.0, 13.0)
    ax.set_aspect("equal", adjustable="box")
    ax.set_xlabel(r"Re($\lambda \Delta t$)")
    ax.set_ylabel(r"Im($\lambda \Delta t$)")
    ax.set_title("Boundary of the stability regions (unstable inside)")
    handles, labels = ax.get_legend_handles_labels()
    ax.legend(handles[::-1], labels[::-1], loc="upper right", fontsize=10)

    # parasitic root of variable-step BDF2
    ax = axes[1]
    omega = [p[0] for p in data["bdf2ParasiticRoot"]]
    root = [p[1] for p in data["bdf2ParasiticRoot"]]
    ax.plot(omega, root, color=cmap[1], linewidth=1.6, label=r"$|\zeta_2| = \omega^2/(1+2\omega)$")
    ax.axhline(1.0, color="0.4", linewidth=1.0)
    limit = 1.0 + math.sqrt(2.0)
    ax.axvline(limit, color="0.4", linestyle="--", linewidth=1.0)
    ax.text(limit + 0.03, 0.15, r"$1+\sqrt{2}$", color="0.3", rotation=90, va="bottom")
    default = data["bdf2MaxStepSizeRatioDefault"]
    ax.axvline(default, color=cmap[3], linestyle=":", linewidth=1.4)
    ax.text(default - 0.03, 0.15, "BDF1 above", color=cmap[3], rotation=90, va="bottom", ha="right")
    ax.set_xlim(0.0, max(omega))
    ax.set_ylim(0.0, 1.8)
    ax.set_xlabel(r"step size ratio $\omega = \Delta t^n / \Delta t^{n-1}$")
    ax.set_ylabel("modulus of the parasitic root")
    ax.set_title("Variable-step BDF2, constant ratio $\\omega$")
    ax.grid(True, alpha=0.3)
    ax.legend(loc="upper left")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=180)
    print(f"Wrote plot to {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
