import argparse
import json
import pathlib
import sys


def add_slope_triangle(ax, x0, y0, order, width=0.3, color="0.3"):
    """Draw a right-triangle slope marker, labeling the rise with the order p and the run with 1."""
    x1 = x0 * 10**width
    y1 = y0 * 10**(order * width)
    ax.plot([x0, x1, x1, x0], [y0, y0, y1, y0], color=color, linewidth=0.8)
    ax.text(x1 * 10**0.04, (y0 * y1)**0.5, str(order), color=color, ha="left", va="center", fontsize=11)
    ax.text((x0 * x1)**0.5, y0 * 10**-0.12, "1", color=color, ha="center", va="top", fontsize=11)


def plot_panel(ax, plt, curves, title, orders):
    cmap = plt.get_cmap("tab10").colors
    markers = ["o", "s", "^", "D", "v", "P"]
    for i, (data, style) in enumerate(curves):
        dts = [p[0] for p in data["convergence"]]
        errors = [p[1] for p in data["convergence"]]
        ax.loglog(dts, errors, linestyle=style, marker=markers[i % len(markers)], color=cmap[i % len(cmap)],
                  label=f"{data['name']} (p={data['order']})")

    dts = [p[0] for p in curves[0][0]["convergence"]]
    for order in orders:
        anchor = next(data for data, _ in curves if data["order"] == order)
        e0 = anchor["convergence"][0][1]
        ref = lambda dt, p=order: 0.3 * e0 * (dt / dts[0]) ** p
        ax.loglog([dts[0], dts[-1]], [ref(dts[0]), ref(dts[-1])], "k--", linewidth=1.0)
        add_slope_triangle(ax, dts[2], ref(dts[2]), order)

    ax.set_xlabel(r"(mean) time step size $\Delta t$")
    ax.set_ylabel("absolute error at $t=1$")
    ax.set_title(title)
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(loc="lower right", fontsize=9)


def main() -> int:
    parser = argparse.ArgumentParser(description="Plot the observed convergence orders of the BDF methods.")
    parser.add_argument("--input", required=True, help="Input JSON file generated by test_multistepmethods")
    parser.add_argument("--output", required=True, help="Output image file (e.g. png)")
    args = parser.parse_args()

    input_path = pathlib.Path(args.input)
    output_path = pathlib.Path(args.output)
    if not input_path.exists():
        print(f"Input file does not exist: {input_path}", file=sys.stderr)
        return 1

    with input_path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)

    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not found; skipping plot generation.")
        return 0

    plt.rcParams.update({"font.size": 12, "axes.titlesize": 13, "axes.labelsize": 12,
                         "xtick.labelsize": 11, "ytick.labelsize": 11})

    constant = data["constant"]
    variable = data["variable"]
    constantCurves = [(constant[f"bdf{k}"], "-") for k in range(1, 6)] \
        + [(constant["bdf3_lowerorderstartup"], ":")]
    variableCurves = [(variable["bdf1"], "-"), (variable["bdf2"], "-"),
                      (dict(variable["bdf3"], name="BDF3 (taken with BDF2)"), "-"),
                      (variable["bdf2_shortenedstep"], ":")]

    fig, axes = plt.subplots(1, 2, figsize=(13.0, 5.5), constrained_layout=True)
    plot_panel(axes[0], plt, constantCurves, "Constant time step size", [1, 2, 3, 4, 5])
    plot_panel(axes[1], plt, variableCurves, "Variable time step size", [1, 2])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=180)
    print(f"Wrote plot to {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
